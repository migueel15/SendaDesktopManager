// Package binds manages Senda's Hyprland Lua shortcuts.
package binds

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/migueel15/SendaDesktopManager/core/internal/stt"
)

const (
	ModuleName = "senda_binds"
	SubmapName = "senda_stt"
)

var keyPattern = regexp.MustCompile(`^[a-zA-Z0-9_ñÑ]+$`)

var modifierMask = map[string]int{
	"SHIFT": 1, "CTRL": 4, "CONTROL": 4, "ALT": 8, "MOD1": 8,
	"MOD2": 16, "MOD3": 32, "SUPER": 64, "MOD4": 64, "MOD5": 128,
}

func Path() string {
	base := os.Getenv("XDG_CONFIG_HOME")
	if !filepath.IsAbs(base) {
		home, err := os.UserHomeDir()
		if err != nil {
			base = ".config"
		} else {
			base = filepath.Join(home, ".config")
		}
	}
	return filepath.Join(base, "hypr", "modules", ModuleName+".lua")
}

func RequireLine() string { return `require("modules.senda_binds")` }

func NormalizeShortcut(input string) (string, error) {
	parts := strings.Split(input, "+")
	if len(parts) == 0 {
		return "", fmt.Errorf("atajo vacío")
	}
	seen := map[int]bool{}
	var normalized []string
	for _, raw := range parts[:len(parts)-1] {
		mod := strings.ToUpper(strings.TrimSpace(raw))
		mask := modifierMask[mod]
		if mask == 0 || seen[mask] {
			return "", fmt.Errorf("modificador inválido o duplicado: %q", raw)
		}
		seen[mask] = true
		if mod == "CONTROL" {
			mod = "CTRL"
		}
		if mod == "MOD1" {
			mod = "ALT"
		}
		if mod == "MOD4" {
			mod = "SUPER"
		}
		normalized = append(normalized, mod)
	}
	key := strings.TrimSpace(parts[len(parts)-1])
	if !keyPattern.MatchString(key) {
		return "", fmt.Errorf("tecla inválida: %q", key)
	}
	if strings.EqualFold(key, "ñ") {
		key = "ntilde"
	} else {
		key = strings.ToLower(key)
	}
	normalized = append(normalized, key)
	return strings.Join(normalized, " + "), nil
}

func Render(shortcut, executable string) ([]byte, error) {
	combo, err := NormalizeShortcut(shortcut)
	if err != nil {
		return nil, err
	}
	if executable == "" || strings.ContainsAny(executable, "\x00\n\r") {
		return nil, fmt.Errorf("ejecutable inválido")
	}
	// Hyprland may start with a PATH that omits ~/.local/bin. Callers pass
	// os.Executable so the bind keeps working regardless of that environment.
	command := executable
	if strings.ContainsAny(executable, " \t'\"\\$`") {
		command = "'" + strings.ReplaceAll(executable, "'", "'\\''") + "'"
	}
	return []byte(fmt.Sprintf(`-- Generated by Senda. Add %s to hyprland.lua.
hl.bind(%s, hl.dsp.exec_cmd(%s), { submap_universal = true, description = "Senda STT toggle" })
`, RequireLine(), strconv.Quote(combo), strconv.Quote(command+" stt toggle"))), nil
}

func Write(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, ".senda-binds-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := f.Chmod(0o600); err != nil {
		f.Close()
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func runner(run stt.Runner) stt.Runner {
	if run == nil {
		return stt.ExecRunner
	}
	return run
}

func Reload(ctx context.Context, run stt.Runner) error {
	out, err := runner(run)(ctx, nil, "hyprctl", "reload")
	if err != nil || strings.TrimSpace(string(out)) != "ok" {
		return fmt.Errorf("hyprctl reload: %s: %w", strings.TrimSpace(string(out)), commandError(err))
	}
	out, err = runner(run)(ctx, nil, "hyprctl", "configerrors")
	if err != nil || strings.TrimSpace(string(out)) != "" {
		return fmt.Errorf("hyprctl configerrors: %s: %w", strings.TrimSpace(string(out)), commandError(err))
	}
	return nil
}

func commandError(err error) error {
	if err != nil {
		return err
	}
	return errors.New("respuesta inesperada")
}

func Loaded(ctx context.Context, run stt.Runner) (bool, error) {
	out, err := runner(run)(ctx, nil, "hyprctl", "repl", `package.loaded["modules.senda_binds"] ~= nil`)
	if err != nil {
		return false, fmt.Errorf("hyprctl repl: %s: %w", strings.TrimSpace(string(out)), err)
	}
	switch strings.TrimSpace(string(out)) {
	case "true":
		return true, nil
	case "false":
		return false, nil
	default:
		return false, fmt.Errorf("respuesta inesperada de hyprctl repl: %q", strings.TrimSpace(string(out)))
	}
}

func Conflicts(ctx context.Context, run stt.Runner, shortcut string) ([]string, error) {
	combo, err := NormalizeShortcut(shortcut)
	if err != nil {
		return nil, err
	}
	parts := strings.Split(combo, " + ")
	key := parts[len(parts)-1]
	mask := 0
	for _, mod := range parts[:len(parts)-1] {
		mask |= modifierMask[mod]
	}
	out, err := runner(run)(ctx, nil, "hyprctl", "-j", "binds")
	if err != nil {
		return nil, fmt.Errorf("hyprctl -j binds: %s: %w", strings.TrimSpace(string(out)), err)
	}
	var all []struct {
		Modmask     int    `json:"modmask"`
		Submap      string `json:"submap"`
		Key         string `json:"key"`
		Arg         string `json:"arg"`
		Dispatcher  string `json:"dispatcher"`
		Description string `json:"description"`
	}
	if err := json.Unmarshal(out, &all); err != nil {
		return nil, fmt.Errorf("analizar binds de Hyprland: %w", err)
	}
	conflicts := []string{}
	for _, bind := range all {
		if bind.Submap != "" || bind.Modmask != mask || !strings.EqualFold(bind.Key, key) {
			continue
		}
		if bind.Description == "Senda STT toggle" || strings.Contains(bind.Arg, "senda stt toggle") {
			continue
		}
		label := strings.TrimSpace(bind.Description)
		if label == "" {
			label = strings.TrimSpace(bind.Dispatcher + " " + bind.Arg)
		}
		conflicts = append(conflicts, label)
	}
	return conflicts, nil
}

func EnsureDefault(path, executable string) (bool, error) {
	if _, err := os.Stat(path); err == nil {
		return false, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	data, err := Render(stt.DefaultShortcut, executable)
	if err != nil {
		return false, err
	}
	if err := Write(path, data); err != nil {
		return false, err
	}
	return true, nil
}

func RenderDisabled() []byte {
	return []byte("-- Senda shortcuts are disabled. This module stays loadable.\nreturn true\n")
}

// Dictation cancellation through Escape is disabled.
type submap struct{}

func NewSubmap(_ stt.Runner) stt.Submap { return &submap{} }

func (*submap) Enter(context.Context) error { return stt.ErrSubmapUnavailable }

func (*submap) Reset(context.Context) error { return nil }
