// RequireLine imports the generated folder; `senda.init` needs no ?/init.lua
// entry in package.path.
const RequireLine = `require("senda.init")`
const managedReference = RequireLine + ` -- Senda: referencia gestionada`
const legacyRequireLine = `require("modules.senda")`
const legacyManagedReference = legacyRequireLine + ` -- Senda: referencia gestionada`

// ValidateExecutable rejects ephemeral binaries such as those produced by go run.
func ValidateExecutable(exe string) error {
	if !filepath.IsAbs(exe) || strings.HasPrefix(filepath.Clean(exe), filepath.Clean(os.TempDir())+string(os.PathSeparator)) {
		return fmt.Errorf("el ejecutable %s no es persistente; usa un binario de desarrollo o release instalado", exe)
	}
	return nil
}

const moduleHeader = "-- Generado por Senda."

func ReadSettings() (Settings, error) {
	values, err := config.Load(paths.ConfigFile())
	if err != nil {
		return Settings{}, err
	}
	s, err := LoadSettings(values)
	if err != nil {
		return s, err
	}
	// Without knowing what the user defines, Senda generates no monitor at all.
	defs, err := UserDefinitions(MonitorSelector)
	if err != nil {
		s.Displays = nil
	} else {
		s.Displays = withoutClaimed(s.Displays, defs)
	}
	if values[stt.KeyShortcut] == "" {
		old := filepath.Join(filepath.Dir(paths.ConfigDir()), "hypr", "modules", "senda_binds.lua")
		if ok, _ := owned(old, "-- Generated by Senda."); ok {
			if data, e := os.ReadFile(old); e == nil {
				re := regexp.MustCompile(`hl\.bind\(("(?:[^"\\]|\\.)*")`)
				if match := re.FindStringSubmatch(string(data)); len(match) == 2 {
					if value, e := strconv.Unquote(match[1]); e == nil {
						if value, e = binds.NormalizeShortcut(value); e == nil {
							s.DictationShortcut = value
						}
					}
				}
			}
		}
	}
	return s, nil
}

func owned(path string, headers ...string) (bool, error) {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if !info.Mode().IsRegular() {
		return false, fmt.Errorf("%s no es un archivo regular; se conserva", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	for _, h := range headers {
		if strings.HasPrefix(string(data), h) {
			return true, nil
		}
	}
	return false, fmt.Errorf("%s no tiene cabecera de Senda; se conserva", path)
}

func checkTarget(path string, headers ...string) error { _, err := owned(path, headers...); return err }

// legacyIdlePath is where hypridle.conf lived, in the shareable folder.
func legacyIdlePath() string { return filepath.Join(paths.ConfigDir(), idleFile) }

// legacyModuleRef matches references to one legacy module, but not to a folder
// that merely starts with its name, such as modules.senda.init.
func legacyModuleRef(name string) *regexp.Regexp {
	stem := regexp.QuoteMeta(strings.TrimSuffix(name, ".lua"))
	return regexp.MustCompile(`modules[./]` + stem + `(?:\.lua)?(?:[^\w./-]|$)`)
}

// Migrate replaces only exact legacy require lines in the main Lua file and
// removes owned legacy files only when no other references can be found. A
// legacy modules/senda.lua that must stay is emptied, because keeping its
// content next to the folder would duplicate every bind.
func Migrate() ([]string, error) {
	var warnings []string
	if ok, err := owned(legacyIdlePath(), idleHeader, "# Archivo de Senda."); err != nil {
		warnings = append(warnings, err.Error())
	} else if ok {
		if w := stopIdleUsing(legacyIdlePath()); w != "" {
			warnings = append(warnings, w)
		}
		if err := os.Remove(legacyIdlePath()); err != nil {
			return warnings, err
		}
	}
	hypr := filepath.Join(filepath.Dir(paths.ConfigDir()), "hypr")
	realHypr, err := filepath.EvalSymlinks(hypr)
	if errors.Is(err, os.ErrNotExist) {
		return warnings, nil
	}
	if err != nil {
		return warnings, err
	}
	main := filepath.Join(realHypr, "hyprland.lua")
	legacy := []struct{ name, header, line string }{
		{"senda_binds.lua", "-- Generated by Senda.", `require("modules.senda_binds")`},
		{"senda-lock.lua", "-- Archivo de Senda:", `require("modules.senda-lock")`},
		{"senda.lua", moduleHeader, legacyRequireLine},
	}
	for _, old := range legacy {
		path := filepath.Join(realHypr, "modules", old.name)
		ok, err := owned(path, old.header)
		if err != nil {
			warnings = append(warnings, err.Error())
			continue
		}
		if !ok {
			continue
		}
		isOld := func(line string) bool {
			line = strings.TrimSpace(line)
			return line == old.line || (old.name == "senda.lua" && line == legacyManagedReference)
		}
		ref := legacyModuleRef(old.name)
		unsafeRef := false
		err = filepath.WalkDir(realHypr, func(p string, d os.DirEntry, e error) error {
			if e != nil {
				return e
			}
			if d.IsDir() || p == path {
				return nil
			}
			if d.Type()&os.ModeSymlink != 0 {
				unsafeRef = true
				return nil
			}
			if !strings.HasSuffix(p, ".lua") && !strings.HasSuffix(p, ".conf") {
				return nil
			}
			b, e := os.ReadFile(p)
			if e != nil {
				return e
			}
			for _, line := range strings.Split(string(b), "\n") {
				if ref.MatchString(line) && (p != main || !isOld(line)) {
					unsafeRef = true
				}
			}
			return nil
		})
		if err != nil {
			return warnings, err
		}
		if unsafeRef {
			warnings = append(warnings, "Módulo antiguo conservado por referencias o enlaces que requieren revisión: "+path)
			if old.name == "senda.lua" {
				if err := binds.Write(path, []byte(moduleHeader+" Migrado a la carpeta senda; se puede borrar.\n")); err != nil {
					return warnings, err
				}
			}
			continue
		}
		data, err := os.ReadFile(main)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return warnings, err
		}
		if err == nil {
			info, err := os.Lstat(main)
			if err != nil {
				return warnings, err
			}
			if !info.Mode().IsRegular() {
				warnings = append(warnings, "Configuración principal no regular; revisa manualmente "+old.line)
				continue
			}
			lines := strings.Split(string(data), "\n")
			changed := false
			for i, line := range lines {
				if isOld(line) {
					lines[i] = managedReference
					changed = true
				}
			}
			if changed {
				seen := false
				out := lines[:0]
				for _, line := range lines {
					if strings.TrimSpace(line) == managedReference {
						if seen {
							continue
						}
						seen = true
					}
					out = append(out, line)
				}
				if err := writePreservingMode(main, []byte(strings.Join(out, "\n")), info.Mode().Perm()); err != nil {
					return warnings, err
				}
			}
		}
		if err := os.Remove(path); err != nil {
			return warnings, err
		}
	}
	return warnings, nil
}

func writePreservingMode(path string, data []byte, mode os.FileMode) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".senda-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err = f.Chmod(mode); err == nil {
		_, err = f.Write(data)
	}
	if e := f.Close(); err == nil {
		err = e
	}
	if err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

// RemoveManaged removes only files and references carrying Senda's markers.
func RemoveManaged() ([]string, error) {
	var warnings []string
	dir := Dir()
	for name, headers := range generatedTargets() {
		path := filepath.Join(dir, name)
		ok, err := owned(path, headers...)
		if err != nil {
			warnings = append(warnings, err.Error())
			continue
		}
		if ok {
			if err := os.Remove(path); err != nil {
				return warnings, err
			}
		}
	}
	// Only an empty folder goes: anything else in it is the user's.
	if err := os.Remove(dir); err != nil && !errors.Is(err, os.ErrNotExist) {
		warnings = append(warnings, "Carpeta conservada porque no está vacía: "+dir)
	}
	main := filepath.Join(filepath.Dir(paths.ConfigDir()), "hypr", "hyprland.lua")
	info, err := os.Lstat(main)
	if errors.Is(err, os.ErrNotExist) {
		return warnings, nil
	}
	if err != nil {
		return warnings, err
	}
	if !info.Mode().IsRegular() {
		return append(warnings, "No se ha modificado hyprland.lua: no es un archivo regular"), nil
	}
	data, err := os.ReadFile(main)
	if err != nil {
		return warnings, err
	}
	lines := strings.Split(string(data), "\n")
	out := lines[:0]
	changed := false
	for _, line := range lines {
		if t := strings.TrimSpace(line); t == managedReference || t == legacyManagedReference {
			changed = true
			continue
		}
		out = append(out, line)
	}
	if changed {
		err = writePreservingMode(main, []byte(strings.Join(out, "\n")), info.Mode().Perm())
	}
	if strings.Contains(strings.Join(out, "\n"), RequireLine) {
		warnings = append(warnings, "Retira manualmente "+RequireLine+" de tu configuración de Hyprland.")
	}
	return warnings, err
}
