func tempConfig(t *testing.T) string {
	t.Helper()
	base := t.TempDir()
	t.Setenv("HOME", base)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(base, "config"))
	t.Setenv("HYPRLAND_INSTANCE_SIGNATURE", "")
	return filepath.Join(base, "config", "hypr")
}
func put(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}
func read(t *testing.T, path string) string {
	t.Helper()
	b, e := os.ReadFile(path)
	if e != nil {
		t.Fatal(e)
	}
	return string(b)
}

func TestMigrationImportsAndRetiresOwnedModules(t *testing.T) {
	hypr := tempConfig(t)
	legacy := filepath.Join(hypr, "modules", "zenda_binds.lua")
	lock := filepath.Join(hypr, "modules", "zenda-lock.lua")
	put(t, legacy, "-- Generated by Zenda. Add require to hyprland.lua.\nhl.bind(\"SUPER + d\", hl.dsp.exec_cmd(\"zenda stt toggle\"))\n")
	put(t, lock, "-- Archivo de Zenda: cárgalo desde hyprland.lua.\n")
	main := filepath.Join(hypr, "hyprland.lua")
	put(t, main, "-- usuario\nrequire(\"modules.zenda_binds\")\nrequire(\"modules.zenda-lock\")\n")
	s, err := ReadSettings()
	if err != nil || s.DictationShortcut != "SUPER + d" {
		t.Fatalf("import: %+v %v", s, err)
	}
	if err = WriteFiles(s, "/usr/bin/zenda"); err != nil {
		t.Fatal(err)
	}
	if err = SaveSettings(paths.ConfigFile(), s); err != nil {
		t.Fatal(err)
	}
	warnings, err := Migrate()
	if err != nil || len(warnings) > 0 {
		t.Fatalf("migrate: %v %v", warnings, err)
	}
	if _, err = os.Stat(legacy); !os.IsNotExist(err) {
		t.Fatal("old dictation module retained")
	}
	if _, err = os.Stat(lock); !os.IsNotExist(err) {
		t.Fatal("old lock module retained")
	}
	contents := read(t, main)
	if strings.Count(contents, managedReference) != 1 || !strings.Contains(contents, "-- usuario") {
		t.Fatalf("main: %s", contents)
	}
	values, err := config.Load(paths.ConfigFile())
	if err != nil || values[stt.KeyShortcut] != "SUPER + d" {
		t.Fatalf("saved %v %v", values, err)
	}
	warnings, err = RemoveManaged()
	if err != nil || len(warnings) > 0 {
		t.Fatalf("remove: %v %v", warnings, err)
	}
	if strings.Contains(read(t, main), "modules.zenda") {
		t.Fatal("managed reference retained")
	}
	for _, path := range []string{ModulePath(), IdlePath()} {
		if _, err = os.Stat(path); !os.IsNotExist(err) {
			t.Fatalf("file retained %s", path)
		}
	}
}

func TestMigrationPreservesUnknownAndComplexReferences(t *testing.T) {
	hypr := tempConfig(t)
	legacy := filepath.Join(hypr, "modules", "zenda_binds.lua")
	put(t, legacy, "-- Generated by Zenda.\n")
	main := filepath.Join(hypr, "hyprland.lua")
	put(t, main, "require(\"modules.zenda_binds\")\n")
	extra := filepath.Join(hypr, "extra.lua")
	put(t, extra, "local x = require(\"modules.zenda_binds\")\n")
	warnings, err := Migrate()
	if err != nil || len(warnings) == 0 {
		t.Fatalf("missing warning %v %v", warnings, err)
	}
	if !strings.Contains(read(t, main), "zenda_binds") {
		t.Fatal("modified reference")
	}
	_ = read(t, legacy)
	put(t, ModulePath(), "usuario\n")
	if err := WriteFiles(DefaultSettings(), "/usr/bin/zenda"); err == nil {
		t.Fatal("overwrote user module")
	}
	if read(t, ModulePath()) != "usuario\n" {
		t.Fatal("changed user module")
	}
}

func TestUninstallPreservesUserFiles(t *testing.T) {
	hypr := tempConfig(t)
	main := filepath.Join(hypr, "hyprland.lua")
	put(t, main, "require(\"modules.zenda\")\n")
	put(t, ModulePath(), "usuario\n")
	put(t, IdlePath(), "usuario\n")
	warnings, err := RemoveManaged()
	if err != nil || len(warnings) < 2 {
		t.Fatalf("warnings %v %v", warnings, err)
	}
	if read(t, ModulePath()) != "usuario\n" || read(t, IdlePath()) != "usuario\n" || read(t, main) != "require(\"modules.zenda\")\n" {
		t.Fatal("changed user file")
	}
}
